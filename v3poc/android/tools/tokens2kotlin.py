#!/usr/bin/env python3
"""Generate AATokens.kt from v3poc/design/tokens.json (the iOS-derived design tokens).

Run: python3 -I v3poc/android/tools/tokens2kotlin.py [--check]
Use --check to detect source/generated drift without writing files.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "design/tokens.json"
OUT = ROOT / "android/app/src/main/java/dev/agentsanywhere/v3poc/design/AATokens.kt"


def camel(name):
    return re.sub(r"^[A-Z]", lambda m: m.group(0).lower(), name)


def color(hex_rgba):
    h = hex_rgba.lstrip("#")
    r, g, b, a = h[0:2], h[2:4], h[4:6], h[6:8]
    return f"Color(0x{a}{r}{g}{b})".upper().replace("COLOR(0X", "Color(0x")


def main():
    t = json.loads(SRC.read_text())
    colors = "\n".join(f"    val {k}: Color,\n" for k in t["color"]).replace("\n\n", "\n")
    light = "\n".join(f"    {k} = {color(v[0])}," for k, v in t["color"].items())
    dark = "\n".join(f"    {k} = {color(v[1])}," for k, v in t["color"].items())
    fonts = "\n".join(f"    val {k} = AAFont({v[0]}f, {v[1]}f, {v[2]})" for k, v in t["font"].items())
    metrics = []
    for k, v in t["metric"].items():
        if isinstance(v, float) or k.endswith(("Fraction", "Scale", "Opacity")):
            metrics.append(f"    const val {k}: Float = {float(v)}f")
        else:
            metrics.append(f"    val {k}: Dp = {v}.dp")
    motion = []
    for k, v in t.get("spring", {}).items():
        motion.append(f"    val {k}: androidx.compose.animation.core.SpringSpec<Float> = "
                      f"androidx.compose.animation.core.spring(dampingRatio = {float(v['dampingRatio'])}f, "
                      f"stiffness = {float(v['stiffness'])}f)")
    for k, v in t["motion"].items():
        args = ", ".join(f"{camel(a)} = {float(b)}f" for a, b in v.items())
        motion.append(f"    val {k} = AAMotionSpec({args})")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    generated = f"""// GENERATED by v3poc/android/tools/tokens2kotlin.py from v3poc/design/tokens.json. Do not edit.
package dev.agentsanywhere.v3poc.design

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/** Colours for one appearance (light or dark), from tokens.json `color`. */
class AAColors(
{colors.rstrip()}
)

val AALightColors = AAColors(
{light}
)

val AADarkColors = AAColors(
{dark}
)

/** iOS Dynamic Type at the default size: size and line height in sp-equivalents (pt), CSS-like weight. */
data class AAFont(val size: Float, val lineHeight: Float, val weight: Int)

object AAFonts {{
{fonts}
}}

object AAMetrics {{
{chr(10).join(metrics)}
}}

/** Springs as SwiftUI writes them (response, dampingRatio) or `.smooth(duration:)`. Unused fields are 0. */
data class AAMotionSpec(
    val response: Float = 0f,
    val dampingRatio: Float = 0f,
    val projectionSeconds: Float = 0f,
    val threshold: Float = 0f,
    val smooth: Float = 0f,
    val scaleFrom: Float = 0f,
    val visibleSeconds: Float = 0f,
)

object AAMotion {{
{chr(10).join(motion)}
}}
"""
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != generated:
            raise SystemExit("AATokens.kt differs from tokens.json; run tokens2kotlin.py to regenerate")
        print("tokens: generated file matches source")
        return
    OUT.write_text(generated)
    print(f"tokens → {OUT.relative_to(ROOT)}")


main()
