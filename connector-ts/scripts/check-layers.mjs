#!/usr/bin/env node
// Layer rules for connector-ts (04-connector.md §2), the counterpart of server/tests/test_architecture_boundaries.py.
// Every static import, re-export, `import type` and dynamic import() under src/ is checked; type-only
// imports count, because a type dependency is still a dependency.
import { readdirSync, readFileSync, statSync } from 'node:fs'
import { dirname, join, relative, resolve, sep } from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

/** I/O modules the pure domain must never touch (node:crypto hashing is allowed). */
const DOMAIN_FORBIDDEN_BUILTINS = new Set([
  'fs', 'fs/promises', 'net', 'tls', 'http', 'https', 'http2', 'dgram', 'dns', 'dns/promises', 'child_process',
  'cluster', 'worker_threads', 'os', 'process', 'readline', 'repl', 'vm', 'inspector', 'sqlite', 'timers', 'timers/promises',
])

/**
 * Contract types generated by scripts/generate-contract-types.mjs: an importable leaf. Every layer,
 * the domain included, may import it; it may import only itself.
 */
const GENERATED = 'generated'

/** Outer implementations of ports; they talk through application/ports, never to each other. */
const PEER_ADAPTERS = new Set(['runtime', 'store', 'link', 'workspace', 'host'])

/**
 * @param {string} file path relative to src/, with '/' separators
 * @returns {{ layer: string, area: string }}
 */
export function classify(file) {
  const [top = '', second = ''] = file.split('/')
  if (top === 'domain') return { layer: 'domain', area: second.endsWith('.ts') ? '' : second }
  if (top === 'application') {
    if (second === 'ports') return { layer: 'application', area: 'ports' }
    if (second === 'inbound') return { layer: 'application', area: 'inbound' }
    return { layer: 'application', area: 'core' }
  }
  return { layer: top.endsWith('.ts') ? '' : top, area: '' }
}

/**
 * @param {{ layer: string, area: string }} from
 * @param {{ layer: string, area: string }} to
 * @returns {string | null} a violation message, or null when allowed
 */
export function ruleViolation(from, to) {
  if (from.layer === GENERATED) return to.layer === GENERATED ? null : 'generated contract types must not import other layers'
  if (to.layer === GENERATED) return null
  if (from.layer === 'domain') {
    if (to.layer !== 'domain') return 'domain must not import other layers'
    if (from.area === 'conversation' && to.area === 'trust') return 'domain/conversation must not import domain/trust'
    return null
  }
  if (from.layer === 'application') {
    if (to.layer === 'domain') return null
    if (to.layer !== 'application') return 'application may depend only on domain and application/ports'
    if (from.area === 'ports' && to.area !== 'ports') return 'application/ports may depend only on domain and application/ports'
    if (from.area === 'core' && to.area === 'inbound') return 'application use cases must not import application/inbound'
    return null
  }
  if (to.layer === 'entry' && from.layer !== 'entry') return 'only entry/ is the composition root; nothing imports it'
  if (PEER_ADAPTERS.has(from.layer) && PEER_ADAPTERS.has(to.layer) && from.layer !== to.layer) {
    return `${from.layer} must not import ${to.layer} directly; go through application/ports`
  }
  return null
}

/** @param {string} directory */
function sourceFiles(directory) {
  /** @type {string[]} */
  const files = []
  for (const name of readdirSync(directory)) {
    const path = join(directory, name)
    if (statSync(path).isDirectory()) files.push(...sourceFiles(path))
    else if (/\.(?:[cm]?ts|tsx)$/.test(name) && !name.endsWith('.d.ts')) files.push(path)
  }
  return files
}

/** @param {string} specifier */
function builtinName(specifier) {
  return specifier.startsWith('node:') ? specifier.slice(5) : null
}

/**
 * @param {string} srcRoot absolute path of src/
 * @returns {string[]} violations
 */
export function checkLayers(srcRoot) {
  /** @type {string[]} */
  const violations = []
  for (const file of sourceFiles(srcRoot)) {
    const fromRelative = relative(srcRoot, file).split(sep).join('/')
    const from = classify(fromRelative)
    const info = ts.preProcessFile(readFileSync(file, 'utf8'), true, true)
    for (const { fileName: specifier } of info.importedFiles) {
      const where = `${fromRelative} -> ${specifier}`
      if (specifier.startsWith('.')) {
        const target = resolve(dirname(file), specifier)
        const toRelative = relative(srcRoot, target).split(sep).join('/')
        if (toRelative.startsWith('..')) {
          violations.push(`${where}: imports outside src/`)
          continue
        }
        const message = ruleViolation(from, classify(toRelative))
        if (message) violations.push(`${where}: ${message}`)
        continue
      }
      if (from.layer === 'domain') {
        const builtin = builtinName(specifier)
        if (builtin !== null && DOMAIN_FORBIDDEN_BUILTINS.has(builtin)) violations.push(`${where}: domain must stay free of I/O`)
        else if (builtin === null) violations.push(`${where}: domain must not depend on packages`)
      }
    }
  }
  return violations
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const srcRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..', 'src')
  const violations = checkLayers(srcRoot)
  if (violations.length) {
    console.error(`Layer violations (${violations.length}):`)
    for (const violation of violations) console.error(`  ${violation}`)
    process.exit(1)
  }
  console.log(`layers ok: ${sourceFiles(srcRoot).length} files checked`)
}
