// frpc configuration for port preview (09-port-preview.md §5.2, §7). One frpc process per device; each open preview
// is one http proxy whose subdomain is the preview slug.
import { WorkspaceError } from '../errors.js'

export interface FrpsEndpoint {
  readonly protocol: 'tcp' | 'websocket' | 'wss'
  readonly host: string
  readonly port: number
}

/**
 * `frpsAddr` from `Commands/previewOpen`: `wss://host[:port]` (default, crosses corporate proxies on 443),
 * `ws://host:port`, `tcp://host:port` or a bare `host:port` (tcp).
 */
export function parseFrpsAddr(value: string): FrpsEndpoint {
  const raw = value.trim()
  const scheme = /^([a-z]+):\/\//iu.exec(raw)?.[1]?.toLowerCase()
  const protocol = scheme === undefined || scheme === 'tcp' ? 'tcp' : scheme === 'wss' ? 'wss' : scheme === 'ws' ? 'websocket' : null
  if (protocol === null) throw new WorkspaceError('invalid_argument', `unsupported frps address: ${value}`)
  let url: URL
  try {
    url = new URL(scheme === undefined ? `tcp://${raw}` : raw)
  } catch {
    throw new WorkspaceError('invalid_argument', `invalid frps address: ${value}`)
  }
  const host = url.hostname.replace(/^\[|\]$/gu, '')
  const port = url.port === '' ? (protocol === 'wss' ? 443 : protocol === 'websocket' ? 80 : NaN) : Number(url.port)
  if (host === '' || !Number.isInteger(port) || port < 1 || port > 65535) {
    throw new WorkspaceError('invalid_argument', `invalid frps address: ${value}`)
  }
  return { protocol, host, port }
}

export interface PreviewProxy {
  readonly previewId: string
  readonly slug: string
  readonly port: number
  readonly localIP: '127.0.0.1' | '::1'
  /** Short-lived token the Server issued for this preview; frps checks it in its NewProxy plugin call. */
  readonly token: string
}

export interface FrpcConfig {
  readonly server: FrpsEndpoint
  /** Login token checked by the frps Login plugin; never stored beyond this config file. */
  readonly loginToken: string
  readonly admin: { readonly port: number; readonly user: string; readonly password: string }
  readonly proxyUrl?: string | null
  readonly proxies: readonly PreviewProxy[]
}

const SLUG = /^[a-z0-9][a-z0-9-]{0,62}$/u

const quote = (value: string): string => JSON.stringify(value)

/** frpc TOML (frp ≥ 0.52). */
export function renderFrpcConfig(config: FrpcConfig): string {
  const lines = [
    '# Generated by Agents Anywhere for port preview. Rewritten on every change; do not edit.',
    `serverAddr = ${quote(config.server.host)}`,
    `serverPort = ${config.server.port}`,
    'loginFailExit = false',
    `metadatas.token = ${quote(config.loginToken)}`,
    `transport.protocol = ${quote(config.server.protocol)}`,
    'transport.heartbeatInterval = 20',
    'webServer.addr = "127.0.0.1"',
    `webServer.port = ${config.admin.port}`,
    `webServer.user = ${quote(config.admin.user)}`,
    `webServer.password = ${quote(config.admin.password)}`,
    'log.to = "console"',
    'log.level = "warn"',
  ]
  if (config.proxyUrl) lines.push(`transport.proxyURL = ${quote(config.proxyUrl)}`)
  for (const proxy of config.proxies) {
    if (!SLUG.test(proxy.slug)) throw new WorkspaceError('invalid_argument', `invalid preview slug: ${proxy.slug}`)
    const host = proxy.localIP === '::1' ? '[::1]' : proxy.localIP
    lines.push(
      '',
      '[[proxies]]',
      `name = ${quote(proxy.slug)}`,
      'type = "http"',
      `subdomain = ${quote(proxy.slug)}`,
      `localIP = ${quote(proxy.localIP)}`,
      `localPort = ${proxy.port}`,
      // Dev servers such as Vite reject unknown Host headers (09 §9).
      `hostHeaderRewrite = ${quote(`${host}:${proxy.port}`)}`,
      `metadatas.previewId = ${quote(proxy.previewId)}`,
      `metadatas.previewToken = ${quote(proxy.token)}`,
    )
  }
  return lines.join('\n') + '\n'
}
