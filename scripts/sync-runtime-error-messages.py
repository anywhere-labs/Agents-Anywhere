#!/usr/bin/env python3
"""Generate client resources for stable runtime error codes.

The table in contracts/runtime-errors/1.0/messages.json is the single source.
Each client shows the entry for a known code in its UI language and falls back
to the server or Connector message only for unknown codes.

Usage: scripts/sync-runtime-error-messages.py [--check]
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import OrderedDict
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]
TABLE = ROOT / "contracts/runtime-errors/1.0/messages.json"
WEB_MESSAGES = [ROOT / "web-next/messages", ROOT / "desktop-workbench/renderer/messages"]
ANDROID_RES = ROOT / "android/app/src/main/res"
ANDROID_KOTLIN = ROOT / "android/app/src/main/java/com/agentsanywhere/app/ui/designsystem/RuntimeErrorText.kt"
IOS_APP = ROOT / "ios/Agents Anywhere/Agents Anywhere"
IOS_CATALOG = IOS_APP / "Resources/Localization/Localizable.xcstrings"
IOS_SWIFT = IOS_APP / "Models/RuntimeErrorText.swift"
HEADER = "Generated by scripts/sync-runtime-error-messages.py from contracts/runtime-errors/1.0/messages.json. Do not edit."


def resource_name(code: str) -> str:
    return "runtime_error_" + code.replace("-", "_")


def android_value(text: str) -> str:
    return escape(text).replace("'", "\\'").replace('"', '\\"')


def swift_literal(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"')


def web_files(messages: dict) -> dict[Path, str]:
    out = {}
    for root in WEB_MESSAGES:
        for lang in ("zh-CN", "en"):
            path = root / f"{lang}.json"
            raw = path.read_text(encoding="utf-8")
            data = json.loads(raw, object_pairs_hook=OrderedDict)
            data["runtimeErrors"] = OrderedDict((code, entry[lang]) for code, entry in messages.items())
            out[path] = json.dumps(data, ensure_ascii=False, indent=2) + ("\n" if raw.endswith("\n") else "")
    return out


def android_files(messages: dict) -> dict[Path, str]:
    out = {}
    for folder, lang in (("values", "en"), ("values-zh-rCN", "zh-CN")):
        lines = [f'<?xml version="1.0" encoding="utf-8"?>', f"<!-- {HEADER} -->", "<resources>"]
        lines += [f'    <string name="{resource_name(code)}">{android_value(entry[lang])}</string>' for code, entry in messages.items()]
        lines.append("</resources>")
        out[ANDROID_RES / folder / "runtime_error_strings.xml"] = "\n".join(lines) + "\n"
    cases = "\n".join(f'    "{code}" -> R.string.{resource_name(code)}' for code in messages)
    out[ANDROID_KOTLIN] = f"""// {HEADER}
package com.agentsanywhere.app.ui.designsystem

import androidx.annotation.StringRes
import com.agentsanywhere.app.R

/** Localized text for a stable runtime or workflow error code, or null for an unknown code. */
@StringRes
fun runtimeErrorRes(code: String?): Int? = when (code) {{
{cases}
    else -> null
}}
"""
    return out


def ios_files(messages: dict) -> dict[Path, str]:
    raw = IOS_CATALOG.read_text(encoding="utf-8")
    catalog = json.loads(raw, object_pairs_hook=OrderedDict)
    strings = catalog["strings"]
    for code, entry in messages.items():
        key = entry["zh-CN"]
        existing = strings.get(key)
        english = existing and existing.get("localizations", {}).get("en", {}).get("stringUnit", {}).get("value")
        if english not in (None, entry["en"]):
            raise SystemExit(f"iOS catalog already maps {key!r} to {english!r}, not {entry['en']!r} ({code})")
        strings[key] = OrderedDict(
            extractionState="manual",
            localizations=OrderedDict(
                en=OrderedDict(stringUnit=OrderedDict(state="translated", value=entry["en"])),
                **{"zh-Hans": OrderedDict(stringUnit=OrderedDict(state="translated", value=key))},
            ),
        )
    cases = "\n".join(f'        case "{code}": String(localized: "{swift_literal(entry["zh-CN"])}")' for code, entry in messages.items())
    swift = f"""// {HEADER}
import Foundation

nonisolated enum RuntimeErrorText {{
    /// Localized text for a stable runtime or workflow error code, or nil for an unknown code.
    static func text(code: String?) -> String? {{
        switch code {{
{cases}
        default: nil
        }}
    }}

    /// The localized text for `code`, else the server or Connector message.
    static func text(code: String?, fallback: String?) -> String? {{ text(code: code) ?? fallback }}
}}
"""
    return {IOS_CATALOG: json.dumps(catalog, ensure_ascii=False, indent=2) + "\n", IOS_SWIFT: swift}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when generated resources are out of date")
    args = parser.parse_args()
    table = json.loads(TABLE.read_text(encoding="utf-8"))
    messages = OrderedDict(sorted(table["messages"].items()))
    for code, entry in messages.items():
        if set(entry) != {"zh-CN", "en"} or not all(isinstance(v, str) and v.strip() for v in entry.values()):
            raise SystemExit(f"{code}: needs non-empty zh-CN and en text")
    files = {**web_files(messages), **android_files(messages), **ios_files(messages)}
    stale = [path for path, text in files.items() if not path.exists() or path.read_text(encoding="utf-8") != text]
    if args.check:
        for path in stale:
            print(f"out of date: {path.relative_to(ROOT)}", file=sys.stderr)
        return 1 if stale else 0
    for path in stale:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(files[path], encoding="utf-8")
        print(f"updated {path.relative_to(ROOT)}")
    print(f"{len(messages)} runtime error codes in sync")
    return 0


if __name__ == "__main__":
    sys.exit(main())
