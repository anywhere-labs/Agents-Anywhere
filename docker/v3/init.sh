#!/usr/bin/env bash
# Writes docker/v3/.env for the self-hosted v3 stack: domains, random secrets and the Router account.
#
#   ./init.sh aa.example.com [--drive]
#
# Uses aa.example.com for the Web app, api.aa.example.com for the control plane, router.aa.example.com for the
# MeshCall Router and, with --drive, files.aa.example.com for the bundled S3. Edit .env afterwards to use other names or
# an external S3 (R2, OSS, AWS) instead of the bundled one. Never overwrites an existing .env.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")"

domain="${1:-}"
drive=0
[[ "${2:-}" == "--drive" ]] && drive=1
if [[ -z "$domain" || "$domain" == -* ]]; then
  echo "usage: $0 <domain> [--drive]" >&2
  exit 2
fi
if [[ -e .env ]]; then
  echo ".env already exists; remove it first if you really want new secrets (existing devices and logins stop working)" >&2
  exit 1
fi

rand() { python3 -c 'import secrets; print(secrets.token_urlsafe(32))'; }
router_password="$(rand)"
router_auth="$(python3 - "$router_password" <<'PY'
import hashlib, json, os, sys
password = sys.argv[1]
salt = os.urandom(16)
key = hashlib.pbkdf2_hmac("sha256", password.encode(), salt, 600000)
services = ["aa.v3.Control", "aa.v3.Sessions", "aa.v3.Terminals", "aa.v3.Device", "aa.v3.DeviceAdmin"]
print(json.dumps({"users": [{
    "username": "control",
    "password_hash": f"pbkdf2-sha256$600000${salt.hex()}${key.hex()}",
    "roles": ["client", "server"],
    "register": services,
    "call": [f"{s}/*" for s in services] + [
        "meshcall.router.v1.AuthService/*", "meshcall.router.v1.TunnelService/*", "meshcall.router.v1.Registry/*"],
}]}, separators=(",", ":")))
PY
)"
setup_token="$(rand)"

umask 077
{
  echo "# Generated by init.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Keep this file secret."
  echo "AA_DOMAIN=$domain"
  echo "AA_API_DOMAIN=api.$domain"
  echo "AA_ROUTER_DOMAIN=router.$domain"
  echo
  echo "POSTGRES_PASSWORD=$(rand)"
  echo "AA_CONTROL_SECRET=$(rand)"
  echo "# Needed once, to create the first (admin) account."
  echo "AA_CONTROL_SETUP_TOKEN=$setup_token"
  echo "# true lets anyone with the address sign up after the first account."
  echo "AA_CONTROL_REGISTRATION_OPEN=false"
  echo
  echo "AA_ROUTER_PASSWORD=$router_password"
  echo "MESHCALL_ROUTER_AUTH='$router_auth'"
  echo
  if [[ "$drive" == 1 ]]; then
    echo "# Cloud drive on the bundled S3 (RustFS) (docker compose --profile drive up -d)."
    echo "AA_FILES_DOMAIN=files.$domain"
    echo "AA_S3_ENDPOINT=http://s3:9000"
    echo "AA_S3_PUBLIC_ENDPOINT=https://files.$domain"
    echo "AA_S3_BUCKET=aa-drive"
    echo "AA_S3_ACCESS_KEY_ID=aa-drive"
    echo "AA_S3_SECRET_ACCESS_KEY=$(rand)"
  else
    echo "# Cloud drive: off. Fill these in for an external S3-compatible bucket, or rerun with --drive for the bundled S3."
    echo "AA_S3_ENDPOINT="
    echo "AA_S3_PUBLIC_ENDPOINT="
    echo "AA_S3_BUCKET=aa-drive"
    echo "AA_S3_ACCESS_KEY_ID="
    echo "AA_S3_SECRET_ACCESS_KEY="
  fi
} > .env

cat <<MSG
Wrote $(pwd)/.env.

Next:
  1. Point DNS for $domain, api.$domain and router.$domain$([[ "$drive" == 1 ]] && echo ", files.$domain") at this machine.
  2. docker compose $([[ "$drive" == 1 ]] && echo "--profile drive ")up -d --build
  3. Create the admin account (once):
       curl -fsS https://api.$domain/auth/register -H 'content-type: application/json' \\
         -d '{"email":"you@example.com","password":"…","display_name":"Admin","setup_token":"$setup_token"}'
  4. Open https://$domain and sign in; on each work machine run the Connector with --control-url https://api.$domain
MSG
