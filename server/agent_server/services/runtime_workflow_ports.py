from typing import Any, Protocol

from agent_server.core.models import ConnectorView, ProjectView, SessionView


class WorkflowRepository(Protocol):
    async def save_user_uploaded_file(self, *, session_id: str, user_id: str, name: str,
                                     data: bytes, media_type: str | None = None,
                                     file_id: str | None = None) -> dict[str, Any]: ...
    async def get_session(self, session_id: str, *, user_id: str) -> SessionView: ...
    async def get_connector(self, connector_id: str) -> ConnectorView: ...
    async def get_project(self, project_id: str, *, user_id: str) -> ProjectView: ...
    async def create_session(self, **values: Any) -> SessionView: ...
    async def put_runtime_workflow(self, row: dict[str, Any]) -> dict[str, Any]: ...
    async def get_runtime_workflow(
        self, identifier: str, *, user_id: str, kind: str
    ) -> dict[str, Any]: ...
    async def set_runtime_workflow_result(
        self, identifier: str, *, user_id: str, kind: str, result: dict[str, Any]
    ) -> None: ...
    async def reject_unreserved_creation(
        self, identifier: str, *, user_id: str, result: dict[str, Any]
    ) -> dict[str, Any]: ...
