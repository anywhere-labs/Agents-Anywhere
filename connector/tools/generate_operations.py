"""Generate operation models, portable contract and clients from the service.

MeshCall 0.3.0's Python CLI returns written:null for this contract. Keep a
small deterministic Python adapter until the pinned upstream generator works.
TypeScript generation uses the official CLI without modification.
"""

import subprocess
import sys
from pathlib import Path

from connector.operations.service import OperationsService
from meshcall import get_service_contract

methods = {method.name for method in get_service_contract(OperationsService).methods}
if methods != {"ping", "submit", "get", "ackResult"}:
    raise RuntimeError(
        "Update the Python adapter generator for the changed service methods"
    )

root = Path(__file__).resolve().parents[2]
contract = root / "contracts/runtime-operations/1.0/service.json"
subprocess.run(
    [
        str(Path(sys.executable).with_name("meshcall")),
        "export",
        "connector.operations.service:OperationsService",
        "--output",
        str(contract),
    ],
    check=True,
)
models = (root / "connector/connector/operations/models.py").read_text()
(root / "server/agent_server/core/operations.py").write_text(
    "# Generated by connector/tools/generate_operations.py. Do not edit.\n" + models
)
(
    root / "server/agent_server/generated/operations.py"
).write_text("""# Generated by connector/tools/generate_operations.py. Do not edit.
from pydantic import BaseModel
from meshcall import Mesh
from agent_server.core.operations import OperationRequest, OperationRecord, ProtocolInfo

class OperationsServiceClient:
    def __init__(self, mesh: Mesh, service: str, instance: str) -> None:
        self.mesh, self.service, self.instance = mesh, service, instance

    async def ping(self) -> ProtocolInfo:
        class Empty(BaseModel):
            pass
        return await self.mesh.call_unary(self.service, "ping", Empty(), ProtocolInfo,
            timeout=5, instance=self.instance)

    async def submit(self, request: OperationRequest) -> OperationRecord:
        class Params(BaseModel):
            request: OperationRequest
        return await self.mesh.call_unary(self.service, "submit", Params(request=request), OperationRecord,
            timeout=10, instance=self.instance, idempotency_key=request.fingerprint())

    async def get(self, operation_id: str) -> OperationRecord | None:
        return await self._receipt("get", operation_id)

    async def ackResult(self, operation_id: str) -> OperationRecord | None:
        return await self._receipt("ackResult", operation_id)

    async def _receipt(self, method: str, operation_id: str) -> OperationRecord | None:
        class Params(BaseModel):
            operationId: str
        return await self.mesh.call_unary(self.service, method, Params(operationId=operation_id),
            OperationRecord | None, timeout=10, instance=self.instance)
""")
subprocess.run(
    [
        str(Path(sys.executable).with_name("meshcall")),
        "generate",
        str(contract),
        "--language",
        "typescript",
        "--single-file",
        "--output",
        str(root / "dsh-bridge-next/src/host/generated/operations.ts"),
    ],
    check=True,
)
