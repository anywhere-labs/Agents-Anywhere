from __future__ import annotations

from typing import Protocol

from ..domain.definitions import LaunchDefinition


class AgentPort(Protocol):
    capabilities: dict

    async def start(self, launch: LaunchDefinition, cwd: str) -> dict: ...
    async def open_session(self, cwd: str) -> dict: ...
    async def prompt(self, session_id: str, text: str, operation_id: str) -> dict: ...
    async def configure(self, session_id: str, key: str, value: str | bool) -> dict: ...
    async def interrupt(self, session_id: str) -> None: ...
    async def close_session(self, session_id: str) -> None: ...
    async def close(self) -> None: ...


class FactPublisher(Protocol):
    async def publish(self, notifications: list[dict]) -> None: ...
