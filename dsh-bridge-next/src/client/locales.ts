export type LocaleKey = keyof typeof en
declare module '@deepseek-ai/dsh-client-ui-slots' {
  interface LocaleNamespaceMap { 'agents-anywhere.next': LocaleKey }
}
export type Translate = TranslateNS<typeof LOCALE_NS>
export const zh = { ...Object.fromEntries(Object.keys(en).map(key => [key, key])), 'locale.code': 'zh-CN' } as Record<LocaleKey, string>

/** Translate known wire messages only at render time, so stored failures change
 * language too. Older Hosts send plain strings; preserve unknown diagnostics
 * and user-provided names/paths instead of guessing or translating log output. */
export function translateMessage(t: Translate, message: string | null | undefined): string {
  if (!message) return ''
  if (Object.hasOwn(en, message)) return t(message as LocaleKey)
  const http = /^服务请求失败（HTTP (\d+)），请重试。$/.exec(message)
  if (http) return t('服务请求失败（HTTP {status}），请重试。', { status: http[1] })
  const exit = /^Connector 已退出（(.+)）。请在日志页切换到 Connector 查看原因。$/.exec(message)
  if (exit) return t('Connector 已退出（{code}）。请在日志页切换到 Connector 查看原因。', { code: exit[1] === '终止' ? t('终止') : exit[1] })
  for (const [prefix, key] of [
    ['无法撤销设备连接。', '无法撤销设备连接。{detail}'],
    ['无法打开 Agents Anywhere 桌面端：', '无法打开 Agents Anywhere 桌面端：{detail}'],
  ] as const) {
    if (message.startsWith(prefix)) return t(key, { detail: translateMessage(t, message.slice(prefix.length)) })
  }
  return message
}
